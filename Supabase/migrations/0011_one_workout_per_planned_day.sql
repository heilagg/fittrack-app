-- 0011: одна живая тренировка на запланированный день (SPEC §3.1, §7.1, §20.3).
--
-- Почему отдельной миграцией: 0001–0010 уже прогнаны, а решение принято после
-- них. Пункт опознан как схемозначимый до кода (server-domain §3), поэтому SPEC
-- правится тем же коммитом, что и эта миграция, и ни строкой позже.
--
-- POST /v1/workouts идемпотентен по planned_day_id (§20.3): офлайновой очереди
-- на вебе нет (§20.10), значит повтор после таймаута — это второе нажатие
-- «Начать», и отвечать на него обязан тот же ответ, а не вторая тренировка.
--
-- Проверкой чтением этого не добиться, и в этом вся причина, по которой
-- ограничение живёт в схеме. Транзакция §20.4 идёт на repeatable read, а он
-- запрещает неповторяющееся чтение, но не фантомную вставку: два параллельных
-- запроса оба не находят тренировки, оба вставляют, и оба правы с точки зрения
-- своего снимка. Ключ идемпотентности, который держит только приложение, — это
-- ключ, которого нет.
--
-- Индекс, а не constraint: частичные unique-ограничения Postgres объявлять не
-- умеет (WHERE в UNIQUE не принимается), а обе половины условия несущие.
--
--   planned_day_id is not null — тренировка вне плана законна, колонка
--   nullable, и NULL в unique-индексе уникальность не ограничивал бы всё равно;
--   условие написано явно, чтобы индекс не рос на строках, которых оно не
--   касается.
--
--   deleted_at is null — мягкое удаление §4.3 обязано ОСВОБОЖДАТЬ день.
--   Без этой половины день, чья тренировка удалена, нельзя было бы начать
--   заново, и восстановление выглядело бы как «день сломан навсегда».
--
-- На непустой базе миграция упадёт, если дубликаты уже есть. Это верное
-- поведение: до неё сервер тренировок не писал вовсе (путь POST /v1/workouts
-- появляется вместе с ней), так что дубликатов взяться неоткуда, а если они
-- есть — их создал не этот код, и молча выбирать из них один нельзя.

create unique index workouts_one_per_planned_day
  on workouts (planned_day_id)
  where planned_day_id is not null and deleted_at is null;

comment on index workouts_one_per_planned_day is
  'Ключ идемпотентности POST /v1/workouts (§20.3): одна незавершённая или '
  'завершённая, но не удалённая тренировка на planned_day. Частичный: NULL — '
  'тренировка вне плана, deleted_at — мягко удалённая освобождает день (§4.3).';
