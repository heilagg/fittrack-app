-- 0009: equipment_profiles.step_platform, equipment_profiles.plyo_box
-- (SPEC §3.1, §6.6).
--
-- Почему отдельной миграцией: 0001–0008 прогнаны, а решение принято после них,
-- до разметки (content-domain §2 п.6, коммит 2fd29ec). §6.6 требует ровно этого
-- порядка — значение словаря инвентаря приходит вместе со своей колонкой, иначе
-- пользовательнице негде отметить снаряд, а разметка ссылается на требование,
-- которое не выполнимо ни на одном профиле.
--
-- Почему сейчас, а не «по факту»: выпад на возвышение и запрыгивание на тумбу
-- входят в распределение §6.1 (ноги/ягодицы 22 из 60–80), и без этих колонок их
-- пришлось бы либо выкинуть из среза, либо разметить с пустым equipment — то
-- есть объявить выполнимыми на голом профиле, где их выполнить не на чем.
-- Введение значения посреди этапа 2 означало бы миграцию поверх уже
-- размеченной библиотеки.
--
-- Почему две колонки, а не одна. Требование — множество допустимых значений
-- колонки (§6.6), и здесь оно асимметрично: тумба годится на месте
-- степ-платформы, платформа на месте тумбы — нет. Предикаты поэтому разные:
-- `step_platform` выполнено при `step_platform or plyo_box`, `plyo_box` —
-- только при `plyo_box`. Одна колонка `box` этого различия не выразила бы, и
-- зашагивание на низкую платформу требовало бы полноразмерной тумбы. Тот же
-- случай, что `bench` с тремя значениями против одного флага.
--
-- Весов у возвышений нет: они не нагружают, а задают высоту, поэтому в лестницу
-- (§9.5) не входят и второго условия выполнимости §6.6 не получают.
--
-- default false, а не not null без умолчания: на существующих строках (их на
-- этом этапе нет, но миграция обязана быть применима к непустой базе) «снаряда
-- нет» — верное значение, а не пропуск ответа. Пресеты §6.6 ставят обе колонки
-- в true только на уровне «зал».

alter table equipment_profiles
  add column step_platform boolean not null default false,
  add column plyo_box      boolean not null default false;

comment on column equipment_profiles.step_platform is
  'Степ-платформа или иное низкое возвышение (§6.6). Требование '
  'step_platform выполнено и тумбой: plyo_box годится на её месте.';

comment on column equipment_profiles.plyo_box is
  'Тумба для запрыгиваний (§6.6). Требование plyo_box платформой НЕ '
  'выполняется — высота и способ приземления другие.';
