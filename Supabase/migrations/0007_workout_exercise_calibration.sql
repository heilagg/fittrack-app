-- 0007: workout_exercises.is_calibration (SPEC §3.1, §9.8, §20.6).
--
-- Почему отдельной миграцией: 0001–0006 уже прогнаны, а решение принято после
-- них. Пункт был опознан как схемозначимый до кода (server-domain §3), поэтому
-- SPEC правится раньше — коммит 5ee78fa.
--
-- Калибровка по §9.8 — свойство УПРАЖНЕНИЯ: выход из неё считается по журналу
-- одного упражнения (два подхода подряд «нормально»/«тяжело» в диапазоне), и
-- состояние живёт в exercise_states.in_calibration. Фильтр же §20.6
-- («калибровочные подходы не идут в утомление §8.1 и в неделя[m] §7.3») стоял
-- по workouts.is_calibration, флагу тренировки, и смешанная тренировка — одно
-- новое упражнение плюс три освоенных — не описывается ни одним его значением:
-- true выбрасывает из учёта три честных упражнения, false засчитывает
-- калибровочные подходы.
--
-- Колонка — СНИМОК exercise_states.in_calibration на момент старта, а не join к
-- нему на чтении: к тому времени, когда подходы попадут в свёртку, состояние
-- уйдёт вперёд (калибровка на то и кончается), и ответ задним числом стал бы
-- другим. Тем же доводом §19.2 п.8 зафиксировал sets.pain_joints на момент
-- события.
--
-- workouts.is_calibration остаётся: баннер §9.8 и аналитика. В расчёт она не
-- идёт вовсе — см. комментарий к ней в §3.1.
--
-- default false, а не not null без умолчания: на уже существующих строках
-- (их на этом этапе нет, но миграция обязана быть применима к непустой базе)
-- «не в калибровке» — верное значение по умолчанию, потому что калибровка
-- кончается, а не начинается сама.

alter table workout_exercises
  add column is_calibration boolean not null default false;

comment on column workout_exercises.is_calibration is
  'Было ли это упражнение в калибровке на момент старта тренировки (§9.8): '
  'снимок exercise_states.in_calibration. По нему, а не по '
  'workouts.is_calibration, калибровочные подходы исключаются из модели '
  'утомления §8.1 и из неделя[m] §7.3.';
