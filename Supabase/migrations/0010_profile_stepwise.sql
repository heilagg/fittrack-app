-- 0010: profiles — четыре колонки становятся nullable (SPEC §3.1, §5, §20.6).
--
-- Почему отдельной миграцией: 0001–0009 прогнаны, а решение принято после них.
-- Пункт схемозначим и закрыт в SPEC до кода (server-domain §1, §3).
--
-- Что произошло. §5 требует, чтобы прерванный онбординг сохранялся пошагово и
-- продолжался с последнего экрана. На iOS это выполнялось локальным хранилищем;
-- на вебе §4.2 признала браузерное хранилище ненадёжным (очистка данных сайта,
-- инкогнито, ITP), поэтому шаги пишутся на сервер по мере прохождения —
-- PATCH /v1/profile (§20.3). Но `experience_level`, `goal`, `days_per_week` и
-- `training_weekdays` заполняются только на шагах 4–6, а объявлены `not null`
-- без умолчания: до шага 6 строку вставить нечем.
--
-- Три выхода рассматривались, и цена названа у выбранного. Ждать шага 6 —
-- значит не выполнить §5 на вебе вовсе. Подставлять умолчания (novice, general,
-- три дня) — значит завести профиль, неотличимый от настоящего выбора, у
-- каждой, кто бросила онбординг на четвёртом экране, и сгенерировать ей неделю
-- как осознанной. Остаётся nullable, и его цена — ниже.
--
-- **Цена: инвариант «строка profiles есть → планировщику есть с чем работать»
-- больше не выполняется.** До этой миграции он держался типом колонки и потому
-- не был записан нигде. Теперь он правило, а не свойство схемы, и живёт в
-- §20.6: профиль полон, когда заполнены все четыре; неполный отсекается ровно в
-- одной точке — POST /v1/week-plans отвечает `profile_incomplete`/409, — и
-- дальше по графу отказ распространяется сам, потому что остальные пути
-- требуют недели.
--
-- Умолчания колонкам НЕ даются, и это то же решение, что отвергнутое выше:
-- умолчание неотличимо от ответа. `null` означает «ещё не спросили», и другого
-- значения у него нет.

alter table profiles
  alter column experience_level  drop not null,
  alter column goal              drop not null,
  alter column days_per_week     drop not null,
  alter column training_weekdays drop not null;

-- Существующие check'и на training_weekdays переживают nullable сами: check
-- считается пройденным на NULL, поэтому `cardinality(...) = days_per_week`,
-- `<@ array[1..7]` и `weekdays_canonical(...)` молчат, пока колонка пуста, и
-- действуют, как только она заполнена. То же у `days_per_week between 1 and 7`.
--
-- Чего они не ловят — заполненную одну из пары. `cardinality(null) = 3` и
-- `cardinality('{1,3,5}') = null` оба дают NULL, то есть проходят. А пара
-- рассогласована ровно тогда, когда одна колонка есть, а другой нет: набор дней
-- задаёт не только количество, но и ТИПЫ дней, потому что сетка §7.2 раздаёт их
-- в календарном порядке. Рассогласование здесь дало бы не отказ, а неделю из не
-- тех дней — молча.
alter table profiles
  add constraint profiles_weekdays_paired
  check ((days_per_week is null) = (training_weekdays is null));

-- Всё вышесказанное замерено на живой базе с применёнными 0001-0009, в
-- откатанной транзакции, ДО коммита (server-domain, чек-лист):
--   строка с четырьмя null                вставляется
--   days_per_week без training_weekdays   profiles_weekdays_paired
--   training_weekdays без days_per_week   profiles_weekdays_paired
--   пара согласованно                     вставляется
--   пара есть, длина не сходится          profiles_check (существующий)
--   набор не канонический                 profiles_training_weekdays_check1
-- Две последние строки — то, ради чего старые check'и не переписывались: они
-- продолжают действовать, как только колонка заполнена.

comment on column profiles.experience_level is
  'null — шаг 4 онбординга ещё не пройден (§5). Профиль считается полным, когда '
  'заполнены все четыре: experience_level, goal, days_per_week, '
  'training_weekdays (§20.6).';
comment on column profiles.goal is
  'null — шаг 5 онбординга ещё не пройден (§5). См. §20.6 о полноте профиля.';
comment on column profiles.days_per_week is
  'null — шаг 6 онбординга ещё не пройден (§5). Заполняется только вместе с '
  'training_weekdays: constraint profiles_weekdays_paired.';
comment on column profiles.training_weekdays is
  'Конкретные дни недели, ISO 1..7, отсортированы (§5 шаг 6, §7.2). null — шаг 6 '
  'ещё не пройден; заполняется только вместе с days_per_week.';
