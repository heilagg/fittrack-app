-- 0006: снимок последнего показанного плана недели (SPEC §3.1, §20.6).
--
-- Почему отдельной миграцией, а не правкой 0003: 0001–0005 уже написаны и
-- прогнаны (коммит eab8f68). Пункт, породивший эту колонку, при составлении
-- таблицы схемозначимых пунктов (скилл server-domain §3) схемозначимым не
-- считался — тогда «генерация недели» выглядела вопросом про порядок вызовов
-- FitCore, а не про хранение. История остаётся честной о том, что это
-- выяснилось позже.
--
-- Колонка нужна ровно одному потребителю: Planner.rebuildNotice сравнивает два
-- ВЫХОДА планировщика и без предыдущего не может решить, печатать ли строку
-- «План обновлён» (§7.1), а молчаливая пересборка там объявлена недопустимой.
--
-- Хранить состав будущего дня больше негде: строки workouts у него нет
-- (тренировка появляется при старте, §7.1), а workout_exercises висит на ней.
-- Пересчитать «как было» тоже нельзя — два триггера из восьми уничтожают свой
-- прежний вход: выполненная тренировка необратимо меняет утомление и
-- неделя[m], а старого инвентаря после правки equipment_profiles в базе просто
-- не остаётся (эту таблицу пишет фронтенд напрямую, §20.6).
--
-- Не путать с input_digest: тот хранит ВХОД и служит отладке, этот — ВЫХОД и
-- участвует в решении, что показать пользовательнице.
--
-- null означает «неделя сгенерирована, но ни разу не показана»: сравнивать не с
-- чем, и строка не печатается.

alter table week_plans
  add column last_shown_plan jsonb;

comment on column week_plans.last_shown_plan is
  'Снимок последнего показанного плана недели (§20.6). Вход для '
  'Planner.rebuildNotice: без предыдущего выхода строка «План обновлён» (§7.1) '
  'невычислима. Не отладочный — для отладки есть input_digest. '
  'null — неделя ни разу не показана.';
