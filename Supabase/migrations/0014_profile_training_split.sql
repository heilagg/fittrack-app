-- 0014: profiles.training_split — схема тренировок (SPEC §3.1, §7.1, §7.2).
--
-- Почему отдельной миграцией: 0001–0013 прогнаны, а решение принято после них
-- и внесено в SPEC до кода (planner-domain §1, server-domain §3).
--
-- Настройка Профиля, а не вопрос онбординга, поэтому умолчание здесь законно —
-- тот же случай, что `session_minutes`, а не четыре колонки 0010: 'auto' значит
-- «расстановка §7.2 по числу дней и уровню», а не «ещё не спросили». Строки,
-- созданные до миграции, получают 'auto' и сетку, которую видели и раньше.
--
-- Значений четыре, и словарь закрыт check'ом: значение вне него `Planner`
-- прочитать не может, а `Mapping/` отдал бы его клиенту как есть. Отдельного
-- сплита по группам мышц нет (§7.2).
--
-- Смена значения уже сгенерированную неделю не трогает (§7.1, как смена
-- `training_weekdays`): `week_plans` и `planned_days` миграция не затрагивает.

alter table profiles
  add column training_split text not null default 'auto'
    check (training_split in ('auto', 'full_body', 'upper_lower', 'push_pull_legs'));
