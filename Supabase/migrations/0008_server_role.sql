-- 0008: роль подключения веб-сервера (§20.4, §3.2).
--
-- Пул `postgres-nio` логинится НЕ владельцем таблиц. Причина замерена, а не
-- предположена: у роли `postgres` в Supabase `rolbypassrls = true`, то есть она
-- обходит все политики §3.2 по атрибуту роли, а не по владению, и
-- `force row level security` её бы не остановил. Вход владельцем означал бы,
-- что изоляция держится на том, что ни один путь не забыл подстановку claims, —
-- а забытая подстановка давала бы не отказ, а молчаливый доступ ко всем строкам
-- всех пользователей. Тест 20a этого не ловит: оба его запроса идут правильным
-- путём.
--
-- `noinherit` — несущее слово, а не стиль. Без него роль получала бы права
-- `authenticated` автоматически при входе, и та же забытая подстановка снова
-- проходила бы молча. С ним первое же чтение без `set_config('role', …)` падает
-- с `permission denied for table …` — замерено.
--
-- Собственных прав роли не выдаётся вовсе, и это работает само: привилегии на
-- таблицы `public` Supabase раздаёт через default privileges ролям `anon`,
-- `authenticated` и `service_role`, среди которых `fitserver` нет. Поэтому
-- отдельного `revoke` здесь нет — отбирать нечего.
--
-- Пароля здесь нет намеренно: он конфигурация среды, а не схемы, и в
-- репозитории ему не место. Локально задаётся отдельно (см.
-- Tests/IntegrationTests/README.md), в проде — при развёртывании.
--
-- Идемпотентно, потому что роль живёт на уровне КЛАСТЕРА, а не базы: повторное
-- применение туда, где она уже есть, иначе упало бы на «role already exists».
--
-- Локальный `supabase db reset` этого не покажет: он кастомные роли УДАЛЯЕТ
-- (замерено пробной ролью — до reset есть, после нет), поэтому там роль каждый
-- раз создаётся заново и ветка `else` не исполняется вовсе. Проверять её нужно
-- повторным применением этого файла, а не вторым `db reset` — иначе тест
-- зелёный по причине, не имеющей отношения к утверждению.
--
-- `grant` ниже обёртки не требует: повторная выдача членства ошибкой не
-- является, только NOTICE.

do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then
    raise exception
      'роль authenticated отсутствует: миграция рассчитана на проект Supabase (§3.2)';
  end if;

  if not exists (select 1 from pg_roles where rolname = 'fitserver') then
    create role fitserver login noinherit;
  else
    -- Роль осталась от прошлого прогона. Атрибуты выравниваются явно: роль,
    -- заведённая руками при отладке, могла оказаться с `inherit`, и тогда всё
    -- правило выше молча перестало бы действовать.
    alter role fitserver login noinherit;
  end if;
end
$$;

grant authenticated to fitserver;

comment on role fitserver is
  'Роль подключения веб-сервера (§20.4): без собственных прав, умеет только '
  'стать authenticated подстановкой set_config(''role'', …, true).';
