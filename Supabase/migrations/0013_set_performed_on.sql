-- 0013: местный день сессии на подходе (SPEC §3.1, §20.7, §20.15 тест 20i).
--
-- §20.7: значения шкалы FitCore приводятся к ней один раз — при записи. День
-- журнала этому правилу не подчинялся: сервер получал его как
-- (workouts.started_at at time zone <зона ТЕКУЩЕГО запроса>)::date, и подход в
-- 01:00 по Москве, прочитанный с зоной Нью-Йорка, переезжал на предыдущий день —
-- а с ним детренированность §9.7, окна флагов боли §8.4 и неделя[m].
--
-- Колонка хранит день СЕССИИ (started_at в зоне запроса, записавшего подход), а
-- не день самого подхода: свёртка группирует по (упражнение, день), и
-- тренировка через полночь не должна распадаться на две сессии.
--
-- Заполнение. Зона, в которой записан существующий подход, нигде не сохранилась:
-- ни у подхода, ни у тренировки, ни в профиле (§20.7 сознательно не хранит её).
-- Единственный день, не выдумывающий зону, — started_at в UTC. Для подхода,
-- записанного восточнее, он может оказаться на сутки раньше местного; это цена
-- за отсутствие данных, а не выбор, и касается только строк до этой миграции.
--
-- Без значения по умолчанию, как в 0012: подход, записанный без дня, должен
-- падать. Заполнение — настоящий update, и триггер sync_seq_bump_parent_upd
-- сдвинет курсор каждой тренировки с подходами один раз; не отключается по
-- тому же доводу, что в 0012.

alter table sets add column performed_on date;

update sets s
   set performed_on = (w.started_at at time zone 'UTC')::date
  from workout_exercises we
  join workouts w on w.id = we.workout_id
 where we.id = s.workout_exercise_id;

alter table sets alter column performed_on set not null;

comment on column sets.performed_on is
  'Местный день сессии (workouts.started_at в зоне запроса записи), шкала FitCore '
  '(§20.7): журнал читает день отсюда, а не переводит started_at при чтении.';
