//  FitAPI — форма границы `/v1` (SPEC §20.2, §20.3).
//
//  Что здесь лежит и почему именно здесь:
//
//  1. **DTO обоих направлений.** Ни один тип `FitCore` не сериализуется сам:
//     там ноль вхождений `Codable`, и это не упущение. `Codable` — stdlib, так
//     что формально ядру её добавить можно; нельзя по другой причине. У enum с
//     ассоциированными значениями (`ReasonCode` и всё вложенное в него)
//     синтезированная форма привязана к именам случаев в Swift, поэтому
//     переименование внутри ядра молча меняло бы проволочный формат у двух
//     развёрнутых клиентов — а §20.8 зафиксировала, что границу такого рода
//     «нельзя поменять никогда». Здесь всё пишется руками: каждый `code` —
//     строковая константа, не зависящая от имени случая.
//
//  2. **Каталог русских формулировок** (`ReasonStrings`). §20.3: сервер отдаёт
//     и код, и готовую строку для всех доменных причин. Каталог живёт в пакете,
//     а не в `Server/`, по той же причине, что и DTO: iOS в офлайне обязан
//     читать тот же каталог, а не писать второй (§4.3, §20.2).
//
//  Чего здесь НЕТ и быть не должно: чтения схемы §3.1 (это `Mapping/` в
//  сервере) и доменных решений (это `FitCore`). Этот пакет только описывает,
//  как посчитанное выглядит на проводе, и как оно называется по-русски.
//
//  Тон формулировок подчиняется §13.5 и §14.6 наравне с экранными — теперь
//  буквально: строки, которые видит пользовательница, приезжают отсюда.

public enum FitAPI {
    /// Версия границы из пути (§20.3). Меняется только вместе с `/vN`.
    public static let version = "v1"
}
