import FitCore

extension ReasonStrings {

    /// Название, «как можно себя чувствовать» и «почему» для фазы на экране.
    public static func phaseText(_ phase: DisplayPhase) -> (name: String, feeling: String, why: String) {
        switch phase {
        case .menstrual:
            return ("Менструация",
                    "Многие в эти дни чувствуют усталость, тянущие ощущения внизу живота или просто меньше сил. У кого-то самочувствие обычное — так тоже бывает.",
                    "Это начало цикла: уровень гормонов, которые меняются по ходу цикла, в эти дни самый низкий.")
        case .follicular:
            return ("После месячных",
                    "Многие замечают, что сил становится больше, а нагрузка переносится легче.",
                    "Обычно это связывают с тем, что в первой половине цикла растёт эстроген.")
        case .ovulatory:
            return ("Середина цикла",
                    "Кто-то чувствует пик энергии, кто-то — лёгкий дискомфорт сбоку внизу живота.",
                    "Примерно в эти дни овуляция. Дата здесь — оценка по прогнозу, а не измерение.")
        case .luteal:
            return ("Вторая половина цикла",
                    "Ближе к месячным многие отмечают усталость, вздутие, перепады настроения, а на тренировке бывает жарче обычного.",
                    "Обычно это связывают с прогестероном во второй половине цикла и со спадом гормонов перед следующими месячными.")
        }
    }

    /// Общая строка под любым текстом фазы (§11.6, связь с §11.7).
    public static let phaseTextNote =
        "Это частые наблюдения, а не диагноз. Как вы себя чувствуете на самом деле, важнее — отметьте это в чек-ине."
}
