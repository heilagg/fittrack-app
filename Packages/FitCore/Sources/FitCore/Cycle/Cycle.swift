//  Cycle — фазы цикла, предсказание, уверенность (SPEC §11).
//
//  Конвейер: CycleHistory.derive → LengthEstimator.expected →
//  PhaseResolver.phase → ConfidenceModel.confidence → CycleState → PhasePolicy.
//
//  Второй вход конвейера, кроме журнала событий, — профиль цикла
//  (cycle_profiles, SPEC §3.1): ConfidenceModel берёт из него declared_regularity,
//  когда измеренных длин меньше двух, а PhaseResolver — typical_period_length_days,
//  когда события period_end нет. Без этого входа regularityFactor на холодном
//  старте выродится в 1.0 для всех — ровно та ошибка, которую сценарий 15
//  (SPEC §18) и должен ловить.
//
//  Границы фаз считаются от овуляции (ovulationDay = expectedLength − 14),
//  а не от дня 1: лютеиновая фаза стабильна, вариативность длины цикла
//  ложится на фолликулярную. menstrualEnd берётся из period_end, иначе из
//  typical_period_length_days, иначе 5 (SPEC §11.1).
//
//  Фазы разрешаются по порядку объявления и не могут перекрываться: на коротких
//  циклах фолликулярная схлопывается в ноль дней (цикл 21 день — сценарий 18a).
//  Пустая фаза — допустимый результат, а не ошибка.
//
//  Числовое влияние фазы масштабируется непрерывно (× confidence) и никогда не
//  обнуляется скачком. Порог 0.3 не участвует в этом расчёте: он разрешает
//  назвать фазу в интерфейсе (SPEC §11.3) и включить категориальные решения
//  (SPEC §11.2) — см. ниже.
//
//  Холодный старт — главный источник ошибок этого модуля, и состояний в нём
//  четыре, а не одно: опорной даты нет вовсе (фаза не вычисляется), ноль
//  измеренных циклов (одна отметка period_start — это ноль, а не один),
//  один цикл (σ ещё не существует, регулярность берётся заявленная),
//  просрочка (recencyFactor вплоть до нуля). SPEC §11.3 описывает все четыре.
//
//  PhasePolicy — канал влияния фазы на ПОДБОР И ОБЪЁМ, но не единственный канал
//  влияния фазы вообще: вторым фаза входит в готовность (phaseTerm, SPEC §10) и
//  через неё — в рекомендованный вес (§9.6). Этот второй путь живёт в модуле
//  Readiness, а не здесь, и искать его в PhasePolicy бесполезно.
//
//  exerciseBias даёт мягкие штрафы в целевую функцию планировщика — для
//  овуляторного ограничения источник признака exercise.impact (SPEC §6.3);
//  жёсткие фильтры остаются только за травмами, инвентарём и болью.
//
//  Числовые поправки (объём, RIR) масштабируются × confidence, категориальные
//  (тип блока, приоритет) включаются только при confidence ≥ 0.3: категорию не
//  на что умножать (SPEC §11.2).
//
//  Границы теста с SPEC §18: этот модуль закрывает 15, 15a, 15b, 16, 17, 18,
//  18a, 19, 19a, 20, 21, 22, 23c, 24, 24b, 24c, 26 — всё, что не требует
//  формулы готовности. 23, 23a (частично — «на готовность действует»), 23b
//  (частично — сама формула замены), 24a, 25, 25a, 25b, 25c читаются в §10 и
//  комбинируют вход отсюда (`effectivePhaseAdjustment`, `cycleConfidence`,
//  `PhasePeriodization`) с чек-ином/утомлением — их место в тестах Readiness,
//  когда этот модуль дойдёт до реализации, не здесь.
