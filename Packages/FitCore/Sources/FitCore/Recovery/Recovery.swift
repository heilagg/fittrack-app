//  Recovery — модель остаточного утомления (SPEC §8).
//
//  Накопление по подходам с учётом fatigue_cost и intensity_factor,
//  экспоненциальный распад с разным периодом полураспада по мышцам
//  (крупные 30 ч, мелкие 20 ч, разгибатели спины 40 ч).
//
//  Утомление поднимает целевой RIR и режет объём, но никогда не блокирует
//  тренировку (SPEC §8.2, §8.3).
//
//  Центральная функция модуля — Recovery.applying(_:at:to:): новое состояние
//  усталости мышцы есть функция (старое значение, прошедшее время, новые
//  подходы) — свёртка того же рода, что rebuildStates(from:) в Progression,
//  но, в отличие от него, не требует полной истории: экспоненциальный
//  распад коммутативен по времени, поэтому достаточно хранить одно значение
//  и метку времени на мышцу (ровно то, что делает таблица `muscle_fatigue`,
//  SPEC §3.1) и применять подходы инкрементально.
//
//  Recovery не знает библиотеки упражнений (contribution/fatigue_cost/
//  joint_stress по конкретному exercise_slug) — это FitContent, от которого
//  FitCore принципиально не зависит. Вызывающая сторона передаёт уже
//  перемноженные contribution×fatigue_cost на подход (FatigueSet.muscleLoad)
//  и сустав для события боли (PainEvent.joint) сама.
//
//  Закрывает SPEC §8.1–§8.4. В номерном списке SPEC §18 модулю не выделено
//  ни одного сценария (1–14 — Progression, 15–26 — Cycle, 27–33 — Planner,
//  34–37 — Sync); сценарий 27 («ягодицы 5 дней подряд») и 25 (оверрайд не
//  снимает защиту утомления) используют Recovery как зависимость, но
//  закрываются тестами Planner. Тесты этого модуля покрывают контракт §8
//  напрямую и помечены `// MARK:`, а не `test_scenarioN`.
