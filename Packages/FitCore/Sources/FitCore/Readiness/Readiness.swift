//  Readiness — сводный множитель готовности (SPEC §10).
//
//  readiness = clamp(1.0 + phaseTerm + checkinAdj×checkinScale + recoveryAdj,
//                    0.75, 1.10)
//
//  phaseTerm — ОДНО слагаемое, а не два: оверрайд подставляется вместо
//  фазовой поправки, а не складывается с ней, и живёт один день (SPEC §11.4).
//  Иначе одна и та же кнопка значила бы разное в разных фазах.
//
//  checkinScale = 1.0 + 0.6×(1 − confidence), в режиме без фаз 1.6: чем меньше
//  известно о цикле, тем больше веса у сегодняшнего чек-ина. Режим без фаз
//  (SPEC §11.5) — предельный случай той же формулы, не отдельная ветка.
//
//  Граница ответственности: readiness — это ЧИСЛО, оно влияет на вес, объём,
//  целевой RIR и сложность подбора (SPEC §10). Утомление (§8) и флаги боли
//  (§8.4) — ЖЁСТКИЕ ФИЛЬТРЫ, применяемые к результату после того, как
//  готовность посчитана. Поэтому push не снимает защиту утомления: он двигает
//  число, а она отсекает варианты. Гарантия в порядке применения, а не в том,
//  что области не пересекаются — они пересекаются.
