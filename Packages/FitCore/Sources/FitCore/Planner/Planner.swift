//  Planner — недельная сетка и сборка конкретной тренировки (SPEC §7).
//
//  WeekPlanner   — расстановка дней, триггеры пересборки, журнал причин.
//  SessionBuilder — жадный отбор упражнений + локальное улучшение по score
//                   (SPEC §7.3). Полный перебор не нужен: 4–7 упражнений
//                   из библиотеки в 60–80 штук.
//
//  Единица объёма — эффективный подход (SPEC §7.4): ведущей мышце упражнения
//  подход засчитывается целиком, остальным — вклад/максимальный вклад. Утомление
//  (§8.1, Recovery) считается по сырым вкладам, и смешивать их нельзя.
//
//  Цель сессии: `S_эфф = норма-старт(ведущая мышца) / Σ её долей за неделю`,
//  дальше `цель[m] = S_эфф × доля[m] × volumeFactor`. `volumeFactor`,
//  `targetRIR`, `weightReadiness`, `sessionSetDelta` — композиции Readiness
//  (§10), которые этот модуль ВЫЗЫВАЕТ, а не реализует заново.
//
//  Score — десять штрафов в эффективных подходах, w1 = 1, идеальная сборка даёт
//  ноль (SPEC §7.3). Бонусов нет намеренно: бонус за упражнение выгодно
//  набирать, добавляя упражнения сверх объёма. Фазе принадлежат w7
//  (`Cycle.exerciseBias`), w8 (приоритет §11.2) и w9 (техническая сложность при
//  готовности < 0.85), причём потолок на сумму w8 + w9 стоит НА УРОВНЕ ОДНОГО
//  УПРАЖНЕНИЯ, внутри суммы: после суммирования он ограничивал бы всю
//  тренировку и правило исчезло бы.
//
//  Состав подбирается по объёму БЕЗ равномерных плановых поправок, подходы — С
//  ними. Поэтому фаза и разгрузочная неделя меняют только target_sets, и строка
//  объяснения «объём снижен» (§7.1) остаётся полной. Утомление по мышцам
//  неравномерно и состав менять обязано (§8.3, п.3).
//
//  Жёсткие ограничения: инвентарь, травмы, флаги боли, skill_level,
//  минимум 3 разных pattern (среди упражнений, работающих на мышцы дня),
//  бюджет времени, не более 2 упражнений из одной progression_family,
//  недельный потолок §7.4 на цель мышцы. Несовместимость разрешается только
//  ослаблением минимума паттернов — безопасность и время не ослабляются.
//
//  Тай-брейки — через инжектируемый seed. При одном входе планировщик
//  обязан давать один и тот же результат, иначе golden-тесты бессмысленны.
//  Seed обязан быть стабильным для пары (пользователь, дата дня): пересборка с
//  неизменившимся входом обязана вернуть ту же тренировку (§7.1).
