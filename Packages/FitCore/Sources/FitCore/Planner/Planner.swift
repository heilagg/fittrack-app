//  Planner — недельная сетка и сборка конкретной тренировки (SPEC §7).
//
//  WeekPlanner   — расстановка дней, триггеры пересборки, журнал причин.
//                  Сетка (SPEC §7.2) зависит только от days_per_week, дней
//                  недели и experience_level; цель, фаза, утомление и прошлый
//                  объём действуют в сборке, не в расстановке. Акцент сетка не
//                  ставит — его выбирает пользователь по дням. 48 часов между
//                  днями одной зоны не проверяются: это работа утомления и w5.
//  SessionBuilder — жадный отбор упражнений + локальное улучшение по score
//                   (SPEC §7.3). Полный перебор не нужен: 4–7 упражнений
//                   из библиотеки в 60–80 штук.
//
//  Единица объёма — эффективный подход (SPEC §7.4): ведущей мышце упражнения
//  подход засчитывается целиком, остальным — вклад/максимальный вклад. Утомление
//  (§8.1, Recovery) считается по сырым вкладам, и смешивать их нельзя.
//
//  Целевой вектор дня — вход, а не константа: таблица (тип дня, акцент) живёт в
//  FitContent (SPEC §7.3), и от её чисел модуль не зависит.
//
//  Цель сессии: `S_эфф = норма-старт(ведущая мышца) / Σ её долей за неделю`,
//  дальше `цель[m] = S_эфф × доля[m] × volumeFactor`. `volumeFactor`,
//  `targetRIR`, `weightReadiness`, `sessionSetDelta` — композиции Readiness
//  (§10), которые этот модуль ВЫЗЫВАЕТ, а не реализует заново. Ведущая мышца —
//  акцентная; без акцента — мышца с наименьшим `норма / Σ долей за неделю`: в
//  однородной неделе это наибольшая доля, в смешанной выбор не зависит от ничьих
//  в плоском векторе (SPEC §7.3). Колонка §7.4 — норма и потолок — по СЕССИИ:
//  акцентная только у акцента этого дня, базовая у остальных, даже если мышца
//  акцентная в другой день; потолок сверяется с недельной суммой.
//
//  Score — одиннадцать штрафов в эффективных подходах, w1 = 1, идеальная
//  сборка даёт ноль (SPEC §7.3). Бонусов нет намеренно: бонус за упражнение
//  выгодно набирать, добавляя упражнения сверх объёма. Фазе принадлежат w7
//  (`Cycle.exerciseBias`), w8 (приоритет §11.2) и w9 (техническая сложность при
//  готовности < 0.85), причём потолок на сумму w8 + w9 стоит НА УРОВНЕ ОДНОГО
//  УПРАЖНЕНИЯ, внутри суммы: после суммирования он ограничивал бы всю
//  тренировку и правило исчезло бы. w11 — покрытие: мышца вектора без единого
//  эффективного подхода за неделю, с весом по кубу её доли и делением на число
//  её оставшихся сессий. Он меняет, какие мышцы получают работу при нехватке
//  времени, но не объём; недобор по времени называет строка статуса недели.
//
//  w10 («на поддержании») пока всегда 0: флаг не хранится, «более сложный
//  вариант» в семье не определён (SPEC §9.5, пп.3–4; §19.2, п.14).
//
//  Состав подбирается по объёму БЕЗ равномерных плановых поправок, подходы — С
//  ними. Поэтому фаза и разгрузочная неделя меняют только target_sets, и строка
//  объяснения «объём снижен» (§7.1) остаётся полной. Утомление по мышцам
//  неравномерно и состав менять обязано (§8.3, п.3).
//
//  Инвентарь (SPEC §6.6, §7.5) — два входа: `EquipmentAvailability` для словаря
//  требований `equipment` и `EquipmentProfile` для лестницы весов. Упражнение
//  выполнимо, если выполнено каждое требование И лестница его `load_type` не
//  пуста. Согласованность флага и набора весов — контракт вызывающей стороны.
//
//  Жёсткие ограничения: инвентарь, травмы, флаги боли, skill_level,
//  минимум 3 разных pattern (среди упражнений, работающих на мышцы дня),
//  бюджет времени, не более 2 упражнений из одной progression_family,
//  недельный потолок §7.4 на цель мышцы. Несовместимость разрешается только
//  ослаблением минимума паттернов — безопасность и время не ослабляются.
//
//  Бюджет времени (SPEC §7.3, «Расчётное время»): переход между упражнениями
//  стоит отдых + setup — отдых считается после КАЖДОГО подхода, включая
//  последний подход упражнения, и НЕ считается после последнего подхода
//  тренировки. Работа в подходе — константа 40 с, ×2 на односторонних; от
//  числа повторов она не зависит, пока не закрыт §9.5 («не реализовано 1 из
//  3») целиком: суженный и фазовые диапазоны. Множитель отдыха
//  — ступенька на порогах готовности §10 (0.9 и 1.05), то же число, что у
//  таймера §13.3. Разминка §12.1 и заминка §12.2 в session_minutes НЕ входят.
//  Нехватка времени ослабляет минимум паттернов так же, как их недоступность,
//  но с другим ReasonCode: второе пользователь изменить не может, первое —
//  одним тапом по session_minutes.
//
//  Повторы и базовый RIR — из цели (SPEC §9.1): target_rep_max = верх +
//  rep_extension; baseRIR — верх RIR цели у новичка, низ у остальных. Итоговый
//  RIR — Readiness.targetRIR; надбавка утомления — если хоть одна нагруженная
//  мышца не восстановлена; +1 консервативного режима (§14.1) — сверх потолка.
//
//  Будущие дни (SPEC §7.1) — от замороженного состояния: утомление только от
//  выполненных подходов с распадом до 12:00 этого дня, `неделя[m]` и
//  предыдущая тренировка — по выполненным, готовность — от фазы на дату дня без
//  check-in и оверрайда. Запланированное не засчитывается выполненным;
//  выполненная тренировка — триггер пересборки оставшихся дней.
//
//  Разгрузочная ли неделя в режиме без фаз (`isDeloadWeek`), модуль не
//  выводит сам: признак передаёт вызывающая сторона, правило счёта открыто
//  (SPEC §11.5, §19.2 п.4).
//
//  Тай-брейки — через инжектируемый seed. При одном входе планировщик
//  обязан давать один и тот же результат, иначе golden-тесты бессмысленны.
//  Seed обязан быть стабильным для пары (пользователь, дата дня): пересборка с
//  неизменившимся входом обязана вернуть ту же тренировку (§7.1).
