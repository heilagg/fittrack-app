//  Шаблон растяжки (SPEC §12.2) — намеренно неполный тип.
//
//  Решение content-domain §2 п.7: схема ПОЗЫ не определена и отложена до этапа
//  В3. §12.1 требует подбора динамической мобильности «по мышцам и паттернам,
//  которые будут в тренировке», а §12.2 — автозаминки «по фактически
//  проработанным мышцам, 3–5 растяжек»; значит у позы есть разметка мышц и
//  длительности, и какая именно — SPEC не говорит. Придумать её здесь значило
//  бы принять продуктовое решение в загрузчике, ровно против content-domain §1.
//
//  Поэтому здесь ровно то, что §12.2 уже зафиксировал таблицей: семь шаблонов
//  с названием, длительностью и назначением. Поз у шаблона нет, каталог
//  `Resources/stretches/` пуст, и `GET /v1/content/stretches` до В3 отдаёт
//  пустой список — валидный ответ со своим `ETag`, а не ошибку (§20.11).
//
//  Тип существует сейчас, а не заводится позже, по одной причине: пустой
//  список обязан быть списком ЧЕГО-ТО, иначе третья поставка (`Server/Content/`)
//  не имеет формы ответа. Расширение его позами — работа В3, и она не
//  совместима с этим типом по построению: поза добавит сюда поле, которого
//  сейчас нет.

/// Шаблон самостоятельной сессии растяжки (SPEC §12.2, таблица семи).
public struct StretchSchema: Sendable, Equatable, Decodable {
    public var slug: String
    public var name: String
    /// Длительность из таблицы §12.2 (7, 10, 8, 12, 10, 12, 20 минут).
    public var durationMinutes: Int
    /// Назначение из той же таблицы — показ, не подбор.
    public var purpose: String

    private enum Key: String, CodingKey {
        case slug, name
        case durationMinutes = "duration_minutes"
        case purpose
    }

    public init(slug: String, name: String, durationMinutes: Int, purpose: String) {
        self.slug = slug
        self.name = name
        self.durationMinutes = durationMinutes
        self.purpose = purpose
    }
}
