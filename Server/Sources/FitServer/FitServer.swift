//  FitServer — Vapor-обёртка над FitCore для веб-версии (SPEC §20).
//
//  У этого модуля нет своего раздела SPEC с алгоритмом: он ничего не считает.
//  Источник архитектуры — §20 целиком, в первую очередь §20.2–§20.9, и этот
//  комментарий написан из него, а не из головы. Все шесть модулей FitCore
//  получили свой doc-комментарий на этапе скелета; Server в скелет не входил, и
//  для него он — первый артефакт модуля, написанный до кода.
//
//  ── Раскладка (§20.2) ──────────────────────────────────────────────────────
//
//    Auth/     — проверка JWT по JWKS, кеш ключей. Ни одной доменной таблицы.
//    DB/       — пул postgres-nio, транзакция запроса, подстановка claims.
//    Mapping/  — схема §3.1 → типы FitCore. Единственное место, где это
//                соответствие существует: iOS-клиент линкует его же, а не
//                пишет второе (§20.2).
//    Routes/   — эндпоинты /v1.
//    Content/  — раздача FitContent с ETag (§20.11).
//
//  ── Чего этот модуль не делает ─────────────────────────────────────────────
//
//  Сервер не делает трёх вещей, и каждая принадлежит кому-то другому:
//  схему читает `Mapping/`, считает `FitCore`, форму на проводе описывает
//  `FitAPI` (§20.2). Второй реализации доменной логики не заводится нигде и
//  ни под каким предлогом (§20.1): §18 покрывает Swift-реализацию, и копия
//  расходилась бы с ней не падением, а тихо неверными весами.
//
//  Русские формулировки живут в `FitAPI`, а не здесь: тот же каталог обязан
//  читать iOS в офлайне (§20.2, §20.3).
//
//  Офлайна у веба нет (§20.10): очереди незаписанных подходов не существует ни
//  в памяти, ни в localStorage. Это не оговорка к §4.3, а другая область
//  действия — требование офлайна остаётся за iOS и за `FitData`.
//
//  ── Конвейер запроса (§20.4) ───────────────────────────────────────────────
//
//    проверка JWT (Auth/, зовёт её сам DB/)
//      → аренда соединения, `begin`
//      → `set transaction isolation level repeatable read`
//      → `set_config('role', …)` + `set_config('request.jwt.claims', …)`
//      → чтение всего входа ОДНИМ срезом (Mapping/)
//      → вызов FitCore
//      → запись домена
//      → ответ (FitAPI)
//
//  Одной транзакцией — не ради скорости: иначе вход несогласован, утомление
//  посчитано до записи тренировки, а `exercise_states` после (§20.4). Одной
//  транзакции для этого, впрочем, мало: `read committed` даёт каждому
//  утверждению свой снимок, поэтому уровень поднят до `repeatable read`, а
//  ценой стал один прозрачный повтор на `40001`.
//
//  ── Изоляция ───────────────────────────────────────────────────────────────
//
//  Второй модели доступа не существует: после подстановки claims политики §3.2
//  действуют буквально, `auth.uid()` возвращает того же пользователя, что и для
//  запроса из браузера, и сервер физически не может прочитать чужую строку.
//  `service_role` на сервере не живёт — единственная операция, которой нужны
//  права выше пользовательских (удаление аккаунта), вынесена в Edge Function, и
//  ключ не покидает Supabase (§20.4, §20.13).
//
//  **Эта гарантия держалась бы на одной строке, и потому не держится на ней.**
//  RLS в миграции `0005` включена без `force`, а у роли `postgres` в Supabase
//  вдобавок `rolbypassrls = true` — она обходит §3.2 по атрибуту роли, так что
//  и `force` её бы не остановил (замерено). Вход владельцем означал бы, что
//  забытая подстановка возвращает все строки всех пользователей, а тест 20a
//  этого не ловит: оба его запроса идут правильным путём.
//
//  Поэтому пул логинится ролью `fitserver` — `noinherit`, без собственных прав,
//  членство только в `authenticated` (миграция `0008`). Забытая подстановка
//  даёт `permission denied` на первом же чтении. И поэтому же арендовать
//  соединение можно только через `Database.withUserTransaction`, который зовёт
//  `Auth/` сам: порядок «сначала проверка, потом БД» стал свойством типа, а не
//  соглашением между слоями.
//
//  ── Аутентификация (§20.5) ──────────────────────────────────────────────────
//
//  Написано: `Auth/`, со своим doc-комментарием и тестом 20b в юнит-части.
//
//  Проверяются пять claims: `exp` (обязателен), `nbf` (если есть — не в
//  будущем), `sub` (он и есть `auth.uid()`), `iss` (issuer проекта), `aud`
//  (`authenticated`). `role` из токена игнорируется безусловно: иначе правило
//  «`service_role` на сервере не живёт» держалось бы на том, что никто не
//  пришлёт токен с другим `role`.
//
//  **Тест 20b («токен другого проекта») закрывается `iss`, а не `aud`**, хотя
//  выглядит наоборот: `aud` у Supabase равен `authenticated` во всех проектах
//  сразу. Промах по `kid` чужой токен тоже отсечёт, но опираться на это значило
//  бы держать обязательный тест зелёным по случайной причине.
//
//  Алгоритмы — закрытый список `{ES256, RS256}`, и берётся алгоритм ИЗ КЛЮЧА,
//  найденного по `kid`, а не из заголовка токена: заголовок не подписан.
//  Отсюда `alg: none`, HS256 на публичном ключе и расхождение заголовка с
//  ключом — три отдельных утверждения в 20b, а не надежда на поведение
//  библиотеки.
//
//  Политики JWKS, каждая со своей ценой:
//    - промах по `kid` — один перезапрос под ДВУМЯ счётчиками: по `kid`
//      (стоит ли этот ключ похода) и глобальным на процесс (можно ли идти
//      сейчас). Одного учёта по `kid` мало: `kid` выбирает присылающий токен,
//      и N неизвестных значений дали бы N запросов в минуту — тот самый рычаг
//      на исходящий трафик, ради которого троттл и введён;
//    - JWKS недоступен при живом кеше — работаем по кешу: ключ не протух от
//      того, что Supabase недоступен;
//    - кеша нет вовсе — `jwks_unavailable` и 503, а НЕ 401: это не «токен
//      плохой», и клиенту следует повторить, а не разлогинивать пользователя;
//    - обновление заменяет набор целиком: объединение со старым не даёт
//      отозванному ключу покинуть кеш никогда.
//
//  Перекос часов для `exp`/`nbf` — 60 секунд, двумя разными моментами: `exp`
//  прощается в прошлое, `nbf` в будущее. С суточным допуском §20.7 его путать
//  нельзя: там сверяются часы телефона с сервером, тут — часы сервера с
//  Supabase, обе машины по NTP.
//
//  `is_anonymous` подлинности не касается — токен анонимного пользователя
//  валиден, потому что §4.1 требует анонимного онбординга, а `profiles` пишет
//  только сервер (§20.6). Гейт линковки отдаёт `unlinked_account`/403 и живёт
//  на сервере, а не в кнопке: правило, оставленное интерфейсу, пришлось бы
//  написать второй раз в iOS и обходилось бы запросом мимо интерфейса.
//
//  Issuer — одно значение из конфигурации, без умолчания; адрес JWKS выводится
//  из него, чтобы подписи и `iss` не могли разойтись по проектам. Дальше в
//  `request.jwt.claims` уходит полезная нагрузка ДОСЛОВНО (§20.4): пересобранный
//  JSON отбросил бы незнакомые claims молча.
//
//  Обновление набора — каждые 10 минут плюс первый поход при старте; пустой
//  набор, приехавший УСПЕХОМ, старт останавливает, а недоступность — нет.
//  Подробности — в `Auth/Auth.swift`.
//
//  ── Время (§20.7) ──────────────────────────────────────────────────────────
//
//  Шкала FitCore — МЕСТНАЯ, не UTC: `Timestamp` и `CalendarDay` отсчитываются
//  от одной эпохи, полночь дня `d` — это `d × 24` часа, момент оценки дня —
//  `d × 24 + 12` (контракт `Planner.evaluationMoment`). Сервер живёт в UTC,
//  пользовательница — нет, поэтому колонки §3.1 разведены по ролям:
//
//    настоящий момент (аудит, LWW)  `timestamptz`  в расчёт не подставляется
//    значение шкалы FitCore         `timestamp`    muscle_fatigue.updated_at
//    день шкалы FitCore             `date`         exercise_states.last_performed_at
//
//  Конверсия делается ОДИН РАЗ, при записи, в зоне присланного запроса, и не
//  повторяется при чтении. Иначе распад §8.1 едет на смещение зоны: 7 часов
//  дают около 21% по мышце с полураспадом 20 ч, а пороги §8.2 стоят на 0.8 и
//  1.8. Ошибка здесь не падает и не видна в ответе — только весом (тест 20i).
//
//  Единственное значение шкалы, которое строится из колонки первой категории, —
//  `CompletedWorkout.performedAt` из `workouts.finished_at`. Это не исключение,
//  а случай, где шкала не важна: значение служит только упорядочиванию (§7.3,
//  слагаемое w6), а порядок не меняется от общего сдвига. Записано затем, чтобы
//  никто не «починил» безвредное и не подставил туда величину другой шкалы.
//
//  День сервер не берёт из своих часов: клиент присылает локальную дату и
//  IANA-зону в каждом запросе, где день имеет значение, сервер их валидирует до
//  любой записи и отклоняет расхождение больше чем на сутки (`date_skew`, 20d).
//
//  ── userSeed (§20.8) ───────────────────────────────────────────────────────
//
//  `Planner.daySeed` требует `userSeed`, колонки под него нет и не будет:
//
//      userSeed = первые 8 байт SHA-256(канонический uuid, 36 символов,
//                 нижний регистр, UTF-8), big-endian → UInt64
//
//  Цена принята явно: сменить seed невозможно, функция — часть контракта, и
//  менять её нельзя никогда, иначе у всех существующих пользователей разом
//  изменится подбор упражнений без единой видимой причины (тест 20h).
//
//  ── Дерево решений (§20.9) ─────────────────────────────────────────────────
//
//  Дерево — КЕШ ответа FitCore, а не вторая реализация §9.3: строится вызовом
//  `Progression.nextSet`, собственной арифметики весов не содержит, и живёт в
//  `FitAPI`, потому что тот же код однажды понадобится iOS-экрану. Существует
//  ради латентности и ни ради чего больше (§13.2, «один тап на подход»);
//  устойчивостью к обрыву сети не является (§20.10).
//
//  Сервер отдаёт его вперёд, вместе с составом упражнения. Форма — карта
//  состояний, а не вложенное дерево: схождение есть свойство состояний, а не
//  путей, и вложенное кодирование разворачивает те же 17–54 узла в 1483.
//
//  ── Обязанности `Mapping/` (§20.6) ─────────────────────────────────────────
//
//  Слой не только отображает — в полутора десятках мест он обязан ПОСЧИТАТЬ:
//  подставить режим «без фаз» пользователю без `cycle_profiles`, перемножить
//  вклад мышцы на стоимость утомления, обнулить набор гирь при снятом флаге,
//  различить утомление до распада и после, взять `weightReadiness` из
//  `workout_exercises`, а не из `workouts.readiness`. Полный список — в §20.6, и
//  он часть контракта, а не деталь реализации: тот же модуль линкует второй
//  клиент, и разойтись эти два клиента могут только здесь. Ни один тест §20.15
//  большую часть этих ошибок не ловит — они видны только числом.
//
//  ── Обязательные тесты (§20.15) ────────────────────────────────────────────
//
//  20a–20k, одиннадцать сценариев: изоляция двух JWT через HTTP; 401 до похода
//  в БД;
//  совпадение каждой ветки дерева с прямым вызовом `nextSet` плюс три половины,
//  к которым сверка слепа по построению (сам диапазон повторов, лимит
//  калибровки, упражнение без веса); идемпотентность генерации недели; суточный
//  допуск даты; идемпотентный ретрай подхода по клиентскому `id`;
//  иммутабельность завершённого подхода; движение `sync_seq`; `userSeed` против
//  независимой реализации; распад утомления при смене зоны между запросами;
//  изоляция через точку входа `DB/` без HTTP (20k) — предшественник 20a и не
//  его замена.
//
//  `swift test` для этого модуля недостаточен: половина списка требует живого
//  Postgres с применёнными миграциями и включённой RLS. Тест изоляции §20.4
//  обязателен отдельно и существующим тестом §3.2 не заменяется — тот проверяет
//  PostgREST, а сервер ходит другим путём.
//
//  ── Что решено после первого чтения §20 ────────────────────────────────────
//
//  Первый заход на §20 против FitAPI, миграций и doc-комментариев FitCore дал
//  восемь расхождений. Все восемь закрыты правкой SPEC до кода (server-domain
//  §1), и здесь они названы затем, чтобы следующий читающий знал, где искать
//  обоснование, а не выводил его заново:
//
//   - **Числа на момент старта** — `Planner.prescribe` (§20.3). Состав, порядок
//     и `target_sets` считаются по 12:00, а `target_rir`, `weight_readiness` и
//     `prescribed_kg` пересчитываются поверх готового состава. Второй
//     `buildSession` эту роль занять не может: утомление входит и в подбор.
//   - **`week_plans.last_shown_plan`** — `FitAPI.WeekPlanSnapshot`, форма
//     `{"v": 1, "days": {…}}` (§20.6), с обратным чтением в значения FitCore.
//     Пишут снимок только пути, отдающие неделю целиком; `/preview` не пишет, а
//     в `/rebuild` порядок несущий: сначала сравнить, потом перезаписать.
//   - **Тела успешных ответов** — таблица §20.3 и типы `FitAPI`. Дерево §20.9
//     едет полем упражнения, `POST …/sets` отдаёт только его.
//   - **`prescribed_kg` приходит от клиента, `prescribed_reps` — нет** (§20.3):
//     вес подходов со второго назначило дерево во фронтенде, а верх диапазона
//     сервер знает сам.
//   - **Калибровка — свойство упражнения** (§9.8): фильтр утомления и
//     `неделя[m]` стоит по `workout_exercises.is_calibration` (миграция `0007`),
//     флаг тренировки остался баннеру и аналитике.
//   - **`exercise_states.current_rep_*`** пишутся только вместе с сессией и
//     являются снимком последней (§9.1, §20.6).
//   - **Причина дня** едет полным конвертом `{code, params, message}`, а `kind`
//     остаётся строкой; оба словаря перечислены в §20.3.
//
//  ── Чего по-прежнему нет ───────────────────────────────────────────────────
//
//  **`FitContent` пуст**: ни загрузчика, ни типов, ни одного упражнения, ни
//  таблицы целевых векторов — только doc-комментарий и `_schema.example.json`.
//  Без него не существует `Content/`, `ETag` §20.11, вектора дня для
//  `PlannedDay`, `FatigueSet.muscleLoad` и `sets.pain_joints`. Это и есть
//  граница текущего этапа: `Auth/` и `DB/` от него не зависят и написаны
//  раньше, `Mapping/`, `Routes/` и `Content/` — зависят полностью.
//
//  Обе половины 20b при этом уже проверены, и исполняемый таргет для второй не
//  понадобился: «до БД запрос не доходит» оказалось утверждением про аренду
//  соединения, а не про HTTP, и наблюдается оно на самой точке входа `DB/`.
//  Подвижность этого наблюдателя утверждает 20k — без той половины ноль аренд
//  доказывал бы только то, что счётчик сломан.
//
//  Открытые вопросы §19.2, задевающие этап: п. 18 (регион VPS — блокирует
//  деплой, не каркас), п. 17 (`Cycle.applyingClosedCycles` на вебе не вызывает
//  никто), п. 4 (правило разгрузочной недели; до его закрытия `is_deload`
//  всегда `false`).

