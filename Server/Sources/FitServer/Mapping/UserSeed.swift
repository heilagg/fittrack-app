//  `userSeed` планировщика (SPEC §20.8).
//
//  `Planner.daySeed(userSeed:day:)` требует seed, а §3.1 такой колонки не
//  имеет и иметь не будет. Seed ВЫВОДИТСЯ из `user_id`:
//
//      userSeed = первые 8 байт SHA-256(канонический uuid пользователя,
//                 36 символов, нижний регистр, UTF-8), big-endian → UInt64
//
//  Ни миграции, ни поля, ни расхождения между платформами: обе стороны
//  получают одно и то же из того, что уже есть.
//
//  ── Это контракт, а не реализация ──────────────────────────────────────────
//
//  §20.8 принимает цену явно: **сменить seed невозможно**. Любая правка любого
//  шага — регистр, дефисы, кодировка, порядок байт, число байт — разом изменит
//  подбор упражнений у всех существующих пользователей без единой видимой
//  причины. Поэтому каждый шаг ниже назван отдельно и проверяется тестом 20h
//  против независимой реализации на другом языке: своя реализация, сверенная
//  сама с собой, доказывает только то, что она не поменялась с прошлого
//  запуска.
//
//  «Канонический» здесь — ровно то, что печатает Postgres для `uuid`:
//  8-4-4-4-12 с дефисами, нижним регистром, 36 символов. `UUID.uuidString`
//  Foundation даёт ту же форму ВЕРХНИМ регистром, поэтому регистр приводится
//  явно, а не считается совпадающим.

#if canImport(FoundationEssentials)
import FoundationEssentials
#else
import Foundation
#endif
import Crypto

extension Mapping {

    /// Seed пользователя для `Planner.daySeed` (§20.8).
    ///
    /// Принимает `UUID`, а не строку, потому что канонизировать нечего: форму
    /// задаёт сам тип, и единственное, что остаётся, — регистр.
    public static func userSeed(userID: UUID) -> UInt64 {
        userSeed(canonicalUUID: userID.uuidString.lowercased())
    }

    /// Тот же seed от уже канонической строки.
    ///
    /// Существует ради двух вызывающих: `sub` токена приезжает строкой (§20.5),
    /// и тест 20h подаёт сюда те же 36 символов, что и независимая реализация.
    /// Форма НЕ проверяется: проверка здесь означала бы, что у контракта два
    /// входа с разным поведением, а строку в него кладёт `VerifiedToken.subject`,
    /// который уже прошёл разбор токена.
    public static func userSeed(canonicalUUID: String) -> UInt64 {
        let digest = SHA256.hash(data: Data(canonicalUUID.utf8))
        // Первые восемь байт, big-endian. Порядок назван явно и не берётся из
        // `withUnsafeBytes { load(as: UInt64.self) }`: тот отдаёт порядок
        // платформы, то есть little-endian на обеих наших, — и контракт молча
        // зависел бы от архитектуры.
        return digest.prefix(8).reduce(UInt64(0)) { ($0 << 8) | UInt64($1) }
    }
}
