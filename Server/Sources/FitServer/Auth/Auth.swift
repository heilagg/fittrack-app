//  Auth/ — проверка JWT Supabase по JWKS (SPEC §20.5).
//
//  Первый подкаталог `Server/` с кодом, и выбран он первым не по важности:
//  §20.5 — единственная часть §20, которой не нужны ни живой Postgres, ни
//  `FitContent`. Ни одной доменной таблицы здесь нет и быть не может.
//
//  ── Что делает конвейер ────────────────────────────────────────────────────
//
//    заголовок токена → `alg` из закрытого списка? → ключ по `kid` в кеше
//      → алгоритм ключа совпал с заголовком? → проверка подписи
//      → claims с перекосом 60 с → `VerifiedToken`
//
//  Дальше (`DB/`) полезная нагрузка уходит дословно в `request.jwt.claims`
//  (§20.4, §20.5): пересобранный JSON отбросил бы незнакомые claims, и первая
//  же политика, прочитавшая `auth.jwt() ->> 'email'`, получила бы `null` молча.
//
//  ── Почему без Vapor ───────────────────────────────────────────────────────
//
//  Политика §20.5 своя: кеш, два счётчика троттла, 401 против 503. `app.jwt`
//  предлагает одну глобальную коллекцию ключей, в которой этой политике нет
//  места. Заодно тест 20b получается юнитовым, без HTTP-обвязки — что важно,
//  потому что исполняемого таргета ещё нет: роуты зависят от `Mapping/`, а тот
//  от пустого `FitContent`.
//
//  ── Две ловушки JWTKit, из-за которых выбор ключа сделан руками ────────────
//
//  Обе найдены чтением 5.7.1, обе тихие, обе отменяют §20.5, если довериться
//  `JWTKeyCollection.verify` как есть:
//
//  1. **`getSigner` подставляет ключ по умолчанию, когда `kid` не найден.**
//     Первый добавленный ключ становится `default`, и токен с неизвестным или
//     отсутствующим `kid` проверяется им, вместо того чтобы стать промахом.
//     То есть механика §20.5 («промах → перезапрос → 401») не наступила бы
//     никогда, а чужой токен имел бы шанс пройти по чужому ключу. Поэтому
//     `kid` ищется здесь, и в коллекцию кладётся ровно один найденный ключ.
//  2. **Алгоритм берётся из заголовка токена, если у JWK его нет.**
//     `JWK.getKey(for:)` вычисляет `alg ?? self.algorithm`, где `alg` — из
//     заголовка. У JWK без `alg` это прямая дорога к подмене алгоритма.
//     Поэтому ключ без явного `alg` не используется вовсе, а заголовок обязан
//     совпасть с алгоритмом ключа (§20.5).
//
//  ── Чего здесь нет ─────────────────────────────────────────────────────────
//
//  Два решения §20.5 не приняты, и код их не выбирает молча:
//
//  - **TTL кеша.** `AuthConfiguration.refreshInterval` — параметр без значения
//    по умолчанию: назвать его обязан тот, кто собирает конфигурацию, а
//    собирать её пока некому (точки входа нет). `nil` означает «обновлять
//    только по промаху `kid`» — буквальное чтение сегодняшнего §20.5.
//  - **Ответ `200` с пустым списком ключей.** Сегодня трактуется как «ключей
//    нет» → `jwks_unavailable`/503, то есть по букве §20.3. У проекта на
//    legacy HS256 это состояние постоянное и от чужого сбоя неотличимо; нужна
//    ли отдельная классификация — вопрос открыт.

#if canImport(FoundationEssentials)
import FoundationEssentials
#else
import Foundation
#endif

/// Конфигурация проверки токенов (§20.5).
///
/// Issuer — одно значение на процесс и без значения по умолчанию: список
/// открыл бы тест 20b одной дописанной строкой, а умолчание относится к тому
/// же классу молчаливой ошибки, что и проверка подписи ключами не того проекта.
public struct AuthConfiguration: Sendable, Equatable {

    /// Ошибка конфигурации — только при старте процесса, не при запросе.
    public enum Failure: Error, Equatable, Sendable {
        /// Issuer не задан или не является абсолютным URL.
        case issuerNotConfigured(String)
    }

    /// `iss`, с которым обязан совпасть токен. Например
    /// `https://<ref>.supabase.co/auth/v1`, локально —
    /// `http://127.0.0.1:54321/auth/v1`.
    public let issuer: String

    /// Адрес JWKS. Не настраивается отдельно, а выводится из `issuer`:
    /// раздельная настройка допускает расхождение, при котором подписи
    /// проверяются ключами одного проекта, а `iss` — против другого (§20.5).
    public let jwksURL: URL

    /// `aud`, обязательный для Supabase (§20.5). Чужой проект им не
    /// отличается — за это отвечает `issuer`.
    public let audience: String

    /// Перекос часов для `exp` и `nbf` — 60 с (§20.5). С суточным допуском
    /// §20.7 не путать: там часы телефона с сервером, тут сервера с Supabase.
    public let clockSkew: TimeInterval

    /// Троттл по `kid`: за одним и тем же неизвестным ключом второй раз не
    /// ходим (§20.5).
    public let kidThrottle: TimeInterval

    /// Троттл на процесс: сколько бы разных `kid` ни пришло, поход не чаще
    /// раза в минуту. Без него учёт по `kid` оставляет открытым внешний рычаг
    /// на исходящий трафик — `kid` выбирает присылающий токен (§20.5).
    public let globalThrottle: TimeInterval

    /// Как часто обновлять набор ключей помимо промахов по `kid`.
    ///
    /// Значения по умолчанию нет намеренно: решение по §20.5 не принято, и
    /// умолчание было бы им. `nil` — «только по промаху», буквальное чтение
    /// сегодняшнего текста.
    public let refreshInterval: TimeInterval?

    public init(
        issuer: String,
        refreshInterval: TimeInterval?,
        audience: String = "authenticated",
        clockSkew: TimeInterval = 60,
        kidThrottle: TimeInterval = 60,
        globalThrottle: TimeInterval = 60
    ) throws {
        // Пробелы срезаются вручную: `trimmingCharacters(in:)` живёт в полной
        // Foundation, которой на Linux в `FoundationEssentials` нет, а пакет
        // существует ради Linux.
        let trimmed = String(
            issuer.drop(while: \.isWhitespace).reversed().drop(while: \.isWhitespace).reversed()
        )
        guard !trimmed.isEmpty else {
            throw Failure.issuerNotConfigured("issuer не задан")
        }
        let normalized = trimmed.hasSuffix("/") ? String(trimmed.dropLast()) : trimmed
        guard
            let url = URL(string: normalized + "/.well-known/jwks.json"),
            url.scheme == "https" || url.scheme == "http",
            url.host != nil
        else {
            throw Failure.issuerNotConfigured(normalized)
        }
        self.issuer = normalized
        self.jwksURL = url
        self.audience = audience
        self.clockSkew = clockSkew
        self.kidThrottle = kidThrottle
        self.globalThrottle = globalThrottle
        self.refreshInterval = refreshInterval
    }
}
